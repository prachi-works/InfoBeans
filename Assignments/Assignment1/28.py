#  28. A carpet is 5 m long and 4 m wide. Find its price at the rate of $ 205 per square meter.
carpet_length = 5
carpet_wide = 4
rate_per_square= 205

carpet_area = carpet_length * carpet_wide
#total price of carpet

total_cost= carpet_area * rate_per_square

print(f"Area of carpet:{carpet_area}m2")
print(f"Total price is {total_cost:.2f}")
