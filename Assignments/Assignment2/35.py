#  35. Find the surface area of the cylindrical solid whose radius is 7.7 cm and height is 12 cm.

#Dimension of cylindrical solid
# import math
radius = 7.7
height = 12

total_surface_of_cylinderlicalsolid = 2 * 3.14 * radius * (radius + height)

print(f"The toal surface of cylidnrical solid:{total_surface_of_cylinderlicalsolid}")